    raise exception 'Invitation Only is currently supported for Apply Now only';
  end if;

  update public.eaf_v2_gateway_apps
  set mode=p_mode,updated_at=now(),updated_by=auth.uid()
  where app_code=p_app_code;

  insert into public.eaf_v2_gateway_access_log(user_id,event_code,app_code,details)
  values(auth.uid(),'app_mode_change',p_app_code,jsonb_build_object('mode',p_mode));
  return true;
end;
$$;

