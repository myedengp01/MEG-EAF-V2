-- Anonymous/authenticated bearer-token validator. No invitation table SELECT is exposed.
create or replace function public.eaf_v2_gateway_validate_invitation(p_token uuid)
returns table(
  allowed boolean,
  company_code text,
  expires_at timestamptz,
  remaining_uses integer
)
language plpgsql
stable
security definer
set search_path=public,auth
as $$
declare
  v_mode text;
  v_row public.eaf_v2_gateway_invitations%rowtype;
begin
  select mode into v_mode from public.eaf_v2_gateway_apps where app_code='apply';
  if v_mode <> 'invitation_only' then
    return query select false,null::text,null::timestamptz,0;
    return;
  end if;

  select * into v_row
  from public.eaf_v2_gateway_invitations
  where token=p_token
    and revoked_at is null
    and expires_at>now()
    and use_count<max_uses;

  if not found then
    return query select false,null::text,null::timestamptz,0;
  else
    return query select true,v_row.company_code,v_row.expires_at,greatest(0,v_row.max_uses-v_row.use_count);
  end if;
end;
$$;

revoke all on function public.eaf_v2_gateway_validate_invitation(uuid) from public;
grant execute on function public.eaf_v2_gateway_validate_invitation(uuid) to anon,authenticated;

-- Consume one use only after the application submission succeeds in the browser.
create or replace function public.eaf_v2_gateway_consume_invitation(p_token uuid)
returns boolean
language plpgsql
security definer
set search_path=public,auth
as $$
begin
  update public.eaf_v2_gateway_invitations
  set use_count=use_count+1
  where token=p_token
    and revoked_at is null
    and expires_at>now()
    and use_count<max_uses
    and exists(select 1 from public.eaf_v2_gateway_apps where app_code='apply' and mode='invitation_only');
  return found;
end;
$$;

revoke all on function public.eaf_v2_gateway_consume_invitation(uuid) from public;
grant execute on function public.eaf_v2_gateway_consume_invitation(uuid) to anon,authenticated;

