-- ---------------------------------------------------------------------------
-- 5) Central permission helper.
-- ---------------------------------------------------------------------------
create or replace function public.eaf_v2_gateway_can_access(
  p_app_code text,
  p_user_id uuid default auth.uid()
)
returns boolean
language plpgsql
stable
security definer
set search_path=public,auth
as $$
declare
  v_mode text;
  v_perm boolean := false;
  v_admin boolean := false;
begin
  if auth.uid() is null or p_user_id is null or p_user_id <> auth.uid() then
    return false;
  end if;

  select coalesce(v.is_admin,false) or coalesce(v.is_super_admin,false)
    into v_admin
  from public.eaf_v2_staff_permissions v
  where v.user_id=p_user_id;

  if coalesce(v_admin,false) then return true; end if;

  select a.mode into v_mode
  from public.eaf_v2_gateway_apps a
  where a.app_code=p_app_code;

  if not found or v_mode in ('admin_only','disabled') then return false; end if;

  select case p_app_code
    when 'apply' then coalesce(v.can_access_apply,false)
    when 'hr' then coalesce(v.can_access_hr,false)
    when 'jd_manual' then coalesce(v.can_access_jd_manual,false)
    when 'hr_law' then coalesce(v.can_access_hr_law,false)
    else false
  end
  into v_perm
  from public.eaf_v2_staff_permissions v
  where v.user_id=p_user_id;

  return coalesce(v_perm,false);
end;
$$;

revoke all on function public.eaf_v2_gateway_can_access(text,uuid) from public;
grant execute on function public.eaf_v2_gateway_can_access(text,uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- 6) One-call dashboard bootstrap for the signed-in user.
-- ---------------------------------------------------------------------------
create or replace function public.eaf_v2_gateway_my_access()
returns jsonb
language plpgsql
stable
security definer
set search_path=public,auth
as $$
declare
  v_uid uuid := auth.uid();
  v_name text := '';
  v_email text := '';
  v_admin boolean := false;
  v_apps jsonb := '{}'::jsonb;
begin
  if v_uid is null then
    raise exception 'Authentication required' using errcode='42501';
  end if;

  select coalesce(s.full_name,''), coalesce(u.email,'')
    into v_name,v_email
  from auth.users u
  left join public.eaf_staff_profiles s on s.id=u.id
  where u.id=v_uid;

  select coalesce(v.is_admin,false) or coalesce(v.is_super_admin,false)
    into v_admin
  from public.eaf_v2_staff_permissions v
  where v.user_id=v_uid;

  select coalesce(jsonb_object_agg(
    a.app_code,
    jsonb_build_object(
      'name',a.app_name,
      'path',a.app_path,
      'mode',a.mode,
      'allowed',public.eaf_v2_gateway_can_access(a.app_code,v_uid)
    ) order by a.sort_order
  ),'{}'::jsonb)
  into v_apps
  from public.eaf_v2_gateway_apps a;

  return jsonb_build_object(
    'user',jsonb_build_object(
      'id',v_uid,
      'full_name',coalesce(nullif(v_name,''),v_email),
      'email',v_email,
      'is_admin',coalesce(v_admin,false)
    ),
    'apps',v_apps
  );
end;
$$;

revoke all on function public.eaf_v2_gateway_my_access() from public;
grant execute on function public.eaf_v2_gateway_my_access() to authenticated;

-- ---------------------------------------------------------------------------
-- 7) Admin directory with names + emails + gateway permissions.
-- ---------------------------------------------------------------------------
create or replace function public.eaf_v2_gateway_staff_directory()
returns table (
  id uuid,
  full_name text,
  email text,
  account_status text,
  is_admin boolean,
  is_super_admin boolean,
  can_access_apply boolean,
  can_access_hr boolean,
  can_access_jd_manual boolean,
  can_access_hr_law boolean
)
language plpgsql
stable
security definer
set search_path=public,auth
as $$
begin
  if not public.eaf_v2_is_admin(auth.uid()) then
    raise exception 'V2 Administrator access required' using errcode='42501';
  end if;

  return query
  select
    u.id,
    coalesce(nullif(s.full_name,''),u.email,'')::text,
    coalesce(u.email,'')::text,
    case
      when u.banned_until is not null and u.banned_until > now() then 'disabled'
      when u.email_confirmed_at is null then 'pending'
      else 'active'
    end::text,
    coalesce(v.is_admin,false),
    coalesce(v.is_super_admin,false),
    coalesce(v.can_access_apply,false),
    coalesce(v.can_access_hr,false),
    coalesce(v.can_access_jd_manual,false),
    coalesce(v.can_access_hr_law,false)
  from auth.users u
  left join public.eaf_staff_profiles s on s.id=u.id
  left join public.eaf_v2_staff_permissions v on v.user_id=u.id
  where s.id is not null or v.user_id is not null
  order by lower(coalesce(nullif(s.full_name,''),u.email,'')),lower(coalesce(u.email,''));
end;
$$;

revoke all on function public.eaf_v2_gateway_staff_directory() from public;
grant execute on function public.eaf_v2_gateway_staff_directory() to authenticated;

-- ---------------------------------------------------------------------------
-- 8) Admin: per-user gateway access setter.
-- ---------------------------------------------------------------------------
create or replace function public.eaf_v2_gateway_set_user_access(
  p_user_id uuid,
  p_app_code text,
  p_allowed boolean
)
returns boolean
language plpgsql
security definer
set search_path=public,auth
as $$
begin
  if not public.eaf_v2_is_admin(auth.uid()) then
    raise exception 'V2 Administrator access required' using errcode='42501';
  end if;
  if p_user_id is null or p_app_code not in ('apply','hr','jd_manual','hr_law') then
    raise exception 'Valid user and app code are required';
  end if;
  -- Build 10 normally seeds this row when eaf_staff_profiles is created. This
  -- defensive insert also handles any older account whose V2 row was missed.
  insert into public.eaf_v2_staff_permissions(user_id)
  select p.id from public.eaf_staff_profiles p where p.id=p_user_id
  on conflict (user_id) do nothing;

  if not exists(select 1 from public.eaf_v2_staff_permissions where user_id=p_user_id) then
    raise exception 'V2 staff permission profile not found';
  end if;

  update public.eaf_v2_staff_permissions
  set
    can_access_apply = case when p_app_code='apply' then p_allowed else can_access_apply end,
    can_access_hr = case when p_app_code='hr' then p_allowed else can_access_hr end,
    can_access_jd_manual = case when p_app_code='jd_manual' then p_allowed else can_access_jd_manual end,
    can_access_hr_law = case when p_app_code='hr_law' then p_allowed else can_access_hr_law end
  where user_id=p_user_id;

  insert into public.eaf_v2_gateway_access_log(user_id,event_code,app_code,details)
  values(auth.uid(),'permission_change',p_app_code,jsonb_build_object('target_user_id',p_user_id,'allowed',p_allowed));

  return true;
end;
$$;

revoke all on function public.eaf_v2_gateway_set_user_access(uuid,text,boolean) from public;
grant execute on function public.eaf_v2_gateway_set_user_access(uuid,text,boolean) to authenticated;

-- ---------------------------------------------------------------------------
-- 9) Admin: application-mode setter.
-- ---------------------------------------------------------------------------
create or replace function public.eaf_v2_gateway_set_app_mode(
  p_app_code text,
  p_mode text
)
returns boolean
language plpgsql
security definer
set search_path=public,auth
as $$
begin
  if not public.eaf_v2_is_admin(auth.uid()) then
    raise exception 'V2 Administrator access required' using errcode='42501';
  end if;
  if p_app_code not in ('apply','hr','jd_manual','hr_law') then
    raise exception 'Invalid app code';
  end if;
  if p_mode not in ('restricted','invitation_only','admin_only','disabled') then
    raise exception 'Invalid app mode';
