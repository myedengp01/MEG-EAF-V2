-- ---------------------------------------------------------------------------
-- 10) Admin: create/list/revoke Apply Now invitation links.
-- ---------------------------------------------------------------------------
create or replace function public.eaf_v2_gateway_create_invitation(
  p_company_code text,
  p_expires_at timestamptz,
  p_max_uses integer default 1
)
returns table(token uuid,expires_at timestamptz,max_uses integer)
language plpgsql
security definer
set search_path=public,auth
as $$
declare
  v_token uuid := gen_random_uuid();
  v_exp timestamptz := coalesce(p_expires_at,now()+interval '7 days');
  v_max integer := greatest(1,least(coalesce(p_max_uses,1),1000));
  v_mode text;
begin
  if not public.eaf_v2_is_admin(auth.uid()) then
    raise exception 'V2 Administrator access required' using errcode='42501';
  end if;
  if lower(coalesce(p_company_code,'')) not in ('meg','meh','hds','abn') then
    raise exception 'Invalid company code';
  end if;
  if v_exp <= now() then raise exception 'Expiry must be in the future'; end if;

  select mode into v_mode from public.eaf_v2_gateway_apps where app_code='apply';
  if v_mode <> 'invitation_only' then
    raise exception 'Apply Now must be in Invitation Only mode before creating applicant links';
  end if;

  insert into public.eaf_v2_gateway_invitations(token,company_code,expires_at,max_uses,created_by)
  values(v_token,lower(p_company_code),v_exp,v_max,auth.uid());

  insert into public.eaf_v2_gateway_access_log(user_id,event_code,app_code,details)
  values(auth.uid(),'invitation_created','apply',jsonb_build_object('company_code',lower(p_company_code),'expires_at',v_exp,'max_uses',v_max));

  return query select v_token,v_exp,v_max;
end;
$$;

revoke all on function public.eaf_v2_gateway_create_invitation(text,timestamptz,integer) from public;
grant execute on function public.eaf_v2_gateway_create_invitation(text,timestamptz,integer) to authenticated;

